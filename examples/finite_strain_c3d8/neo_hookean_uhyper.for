      SUBROUTINE UHYPER(BI1,BI2,AJ,U,UI1,UI2,UI3,TEMP,NOEL,
     1 CMNAME,INCMPFLAG,NUMSTATEV,STATEV,NUMFIELDV,FIELDV,
     2 FIELDVINC,NUMPROPS,PROPS)
      INCLUDE 'ABA_PARAM.INC'
      CHARACTER*80 CMNAME
      DIMENSION U(2),UI1(3),UI2(6),UI3(6),STATEV(*),FIELDV(*),
     1 FIELDVINC(*),PROPS(*)
      DOUBLE PRECISION SHEAR,LAME,LOGJ
      SHEAR=PROPS(1)
      LAME=PROPS(2)
      LOGJ=LOG(AJ)
      U(1)=SHEAR/2.D0*(BI1*AJ**(2.D0/3.D0)-3.D0)
     1 -SHEAR*LOGJ+LAME/2.D0*LOGJ**2
      U(2)=SHEAR/2.D0*(BI1-3.D0)
      UI1=0.D0
      UI2=0.D0
      UI3=0.D0
      UI1(1)=SHEAR/2.D0*AJ**(2.D0/3.D0)
      UI1(3)=SHEAR/3.D0*BI1*AJ**(-1.D0/3.D0)
     1 -SHEAR/AJ+LAME*LOGJ/AJ
      UI2(3)=-SHEAR/9.D0*BI1*AJ**(-4.D0/3.D0)
     1 +(SHEAR+LAME*(1.D0-LOGJ))/AJ**2
      UI2(5)=SHEAR/3.D0*AJ**(-1.D0/3.D0)
      UI3(4)=-SHEAR/9.D0*AJ**(-4.D0/3.D0)
      UI3(6)=4.D0*SHEAR/27.D0*BI1*AJ**(-7.D0/3.D0)
     1 +(-2.D0*SHEAR+LAME*(2.D0*LOGJ-3.D0))/AJ**3
      RETURN
      END