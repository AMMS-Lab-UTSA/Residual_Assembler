def _abaqus(name):
    a = np.array(_PROBE[name])
    return a.reshape(8, 3, 3).transpose(0, 2, 1) if a.shape[1] == 9 else a


def _increment(integration):
    X = np.array(_PROBE["X"])
    Uf = np.array(_PROBE["U_final"])
    k, n = _PROBE["k"], _PROBE["increments"]
    el = nl.C3D8Nlgeom(X[None], integration)
    inc = el.increment((Uf * (k - 1) / n)[None], (Uf * k / n)[None])
    return el, inc, Uf * k / n


def _rel(a, b):
    return float(np.max(np.abs(np.asarray(a) - np.asarray(b))) / np.max(np.abs(b)))


@pytest.mark.unit
def test_dfgrd_dstran_and_drot_are_what_abaqus_hands_the_umat():
    _, inc, _ = _increment("mean_dilatation")
    assert _rel(inc["Fbar0"][0], _abaqus("DFGRD0")) < 1e-14
    assert _rel(inc["Fbar1"][0], _abaqus("DFGRD1")) < 1e-14
    assert _rel(inc["dstran"][0], _abaqus("DSTRAN")) < 1e-13
    assert _rel(inc["drot"][0], _abaqus("DROT")) < 1e-14


@pytest.mark.unit
def test_the_incoming_stress_and_strain_are_rotated_by_drot():
    _, inc, _ = _increment("mean_dilatation")
    R = inc["drot"][0]
    s_prev = nl.stress_voigt_to_tensor(np.array(_PROBE["STRESSOUT_PREV"]))
    e_prev = nl.strain_voigt_to_tensor(np.array(_PROBE["STRAN_PREV_OUT"]))
    assert _rel(nl.stress_tensor_to_voigt(nl.rotate(R, s_prev)), _abaqus("STRESSIN")) < 1e-13
    assert _rel(nl.strain_tensor_to_voigt(nl.rotate(R, e_prev)), _abaqus("STRAN")) < 1e-13


@pytest.mark.unit
def test_the_reactions_are_the_mean_dilatation_bbar_force_of_the_fbar_material():
    el, _, U = _increment("mean_dilatation")
    f = el.force(U[None], np.array(_PROBE["STRESSOUT"])[None])[0].reshape(8, 3)
    assert _rel(f, np.array(_PROBE["RF"])) < 2e-7          # ODB float32


@pytest.mark.unit
@pytest.mark.parametrize("integration,lower", [("centroid", 1e-4), ("full", 1e-3)])
def test_other_volumetric_treatments_are_measurably_not_abaqus(integration, lower):
    el, inc, U = _increment(integration)
    assert _rel(inc["Fbar1"][0], _abaqus("DFGRD1")) > lower
    f = el.force(U[None], np.array(_PROBE["STRESSOUT"])[None])[0].reshape(8, 3)
    assert _rel(f, np.array(_PROBE["RF"])) > 1e-3
